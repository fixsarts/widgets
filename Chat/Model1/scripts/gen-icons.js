/**
 * One-off dev tool: extracts brand SVG paths (Simple Icons set, via react-icons)
 * and writes src/icons.js + assets/icons/*.svg.
 * Not needed at runtime and not needed to build dist/ — src/icons.js is committed.
 *
 *   NODE_PATH=/path/to/node_modules node scripts/gen-icons.js
 */
const fs = require('fs');
const path = require('path');
const si = require('react-icons/si');

const BRANDS = {
  whatsapp: 'SiWhatsapp', instagram: 'SiInstagram', telegram: 'SiTelegram', discord: 'SiDiscord',
  messenger: 'SiMessenger', facebook: 'SiFacebook', tiktok: 'SiTiktok', x: 'SiX', youtube: 'SiYoutube',
  github: 'SiGithub', line: 'SiLine', snapchat: 'SiSnapchat', signal: 'SiSignal', threads: 'SiThreads',
  pinterest: 'SiPinterest', twitch: 'SiTwitch', spotify: 'SiSpotify', behance: 'SiBehance', dribbble: 'SiDribbble'
};
const COLORS = {
  whatsapp: '#25D366', instagram: '#E4405F', telegram: '#26A5E4', discord: '#5865F2', messenger: '#0099FF',
  facebook: '#1877F2', tiktok: '#25F4EE', x: '#ffffff', youtube: '#FF0000', github: '#ffffff', line: '#06C755',
  snapchat: '#FFFC00', signal: '#3A76F0', threads: '#ffffff', pinterest: '#E60023', twitch: '#9146FF',
  spotify: '#1DB954', behance: '#1769FF', dribbble: '#EA4C89'
};

const brand = {};
for (const [key, comp] of Object.entries(BRANDS)) {
  const tree = si[comp]({});
  const paths = (tree.props.children || []).filter(c => c.type === 'path').map(c => c.props.d);
  if (!paths.length) throw new Error('no path for ' + key);
  brand[key] = paths.join(' ');
  fs.writeFileSync(
    path.join(__dirname, '..', 'assets', 'icons', key + '.svg'),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="${COLORS[key]}"><path d="${brand[key]}"/></svg>\n`
  );
}

